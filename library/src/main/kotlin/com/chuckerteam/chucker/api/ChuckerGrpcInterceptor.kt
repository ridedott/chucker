/**
 * A gRPC [ClientInterceptor] that records calls so they can be inspected in Chucker, next to
 * HTTP traffic. It requires `io.grpc:grpc-api`, which every gRPC Java client already has.
 *
 * Add it to your channel:
 * ```kotlin
 * val channel = OkHttpChannelBuilder.forTarget(target)
 *     .intercept(ChuckerGrpcInterceptor.Builder(context).build())
 *     .build()
 * ```
 *
 * All call types are supported. Each call is recorded as one transaction, with its metadata,
 * trailers, status, and every message sent and received with its timing. Streaming calls update
 * live in Chucker while they run.
 *
 * Messages generated by `protobuf-java` and `protobuf-javalite` are shown as JSON. Other
 * messages are decoded from the wire without a schema, and [GrpcMessageFormatter] lets you
 * customise the output.
 */
public class ChuckerGrpcInterceptor private constructor(
    builder: Builder,
) : ClientInterceptor {
    public constructor(context: Context) : this(Builder(context))

    private val sink: GrpcTransactionSink =
        builder.sink ?: CollectorTransactionSink(builder.collector ?: ChuckerCollector(builder.context))
    private val maxContentLength = builder.maxContentLength
    private val headersToRedact = builder.headersToRedact.mapTo(HashSet()) { it.lowercase() }
    private val renderer = GrpcMessageRenderer(builder.formatters.toList())
    private val skipMethods = builder.skipMethods.toSet()
    private val skipMethodsRegex = builder.skipMethodsRegex.toSet()
    private val skipServices = builder.skipServices.toSet()

    // Recording must never crash the app, whatever goes wrong while a call is saved.
    private val scope =
        CoroutineScope(
            SupervisorJob() + Dispatchers.IO +
                CoroutineExceptionHandler { _, e -> Logger.error("Failed to record a gRPC call", e) },
        )

    override fun <ReqT, RespT> interceptCall(
        method: MethodDescriptor<ReqT, RespT>,
        callOptions: CallOptions,
        next: Channel,
    ): ClientCall<ReqT, RespT> {
        val call = next.newCall(method, callOptions)
        if (shouldSkip(method)) return call
        val authority = callOptions.authority ?: next.authority().orEmpty()
        return RecordingCall(call, method, callOptions, authority)
    }

    private fun shouldSkip(method: MethodDescriptor<*, *>): Boolean {
        val name = method.fullMethodName
        return name in skipMethods || method.serviceName in skipServices || skipMethodsRegex.any { it.matches(name) }
    }

    private inner class RecordingCall<ReqT, RespT>(
        delegate: ClientCall<ReqT, RespT>,
        private val methodDescriptor: MethodDescriptor<ReqT, RespT>,
        private val callOptions: CallOptions,
        private val authority: String,
    ) : ForwardingClientCall.SimpleForwardingClientCall<ReqT, RespT>(delegate) {
        // Set in start(), which the caller can't run concurrently with the other methods.
        @Volatile
        private var recorder: GrpcCallRecorder? = null

        override fun start(
            responseListener: Listener<RespT>,
            headers: Metadata,
        ) {
            val recorder = safely { createRecorder(headers) }
            this.recorder = recorder
            val listener = recorder?.let { RecordingListener(responseListener, it) } ?: responseListener
            try {
                super.start(listener, headers)
            } catch (
                @Suppress("TooGenericExceptionCaught") e: RuntimeException,
            ) {
                // The listener won't be closed, so the call ends here.
                safely { recorder?.onClose(Status.Code.UNKNOWN.value(), null, e, emptyList(), null) }
                throw e
            }
        }

        override fun sendMessage(message: ReqT) {
            safely { recorder?.onMessageSent(message as Any) }
            super.sendMessage(message)
        }

        override fun halfClose() {
            safely { recorder?.onHalfClose() }
            super.halfClose()
        }

        override fun cancel(
            message: String?,
            cause: Throwable?,
        ) {
            safely { recorder?.onCancel(message, cause) }
            super.cancel(message, cause)
        }

        private fun createRecorder(headers: Metadata): GrpcCallRecorder {
            val requestHeaders = headers.toHttpHeaders()
            val transaction =
                HttpTransaction().apply {
                    isGrpc = true
                    requestDate = System.currentTimeMillis()
                    protocol = PROTOCOL
                    this.method = HTTP_METHOD
                    path = "/${methodDescriptor.fullMethodName}"
                    host = hostOf(authority)
                    url = "$authority$path"
                    grpcMethodType = methodDescriptor.type.name
                    grpcDeadlineMs = effectiveDeadline()?.timeRemaining(TimeUnit.MILLISECONDS)
                    requestContentType = GRPC_CONTENT_TYPE
                    setRequestHeaders(requestHeaders)
                    requestHeadersSize = requestHeaders.byteCount()
                }
            return GrpcCallRecorder(
                transaction = transaction,
                authority = authority,
                requestCodec = MarshallerCodec(methodDescriptor.requestMarshaller),
                responseCodec = MarshallerCodec(methodDescriptor.responseMarshaller),
                renderer = renderer,
                maxContentLength = maxContentLength,
                sink = sink,
                scope = scope,
            )
        }

        // The deadline set on the call, or the one inherited from the gRPC context if earlier.
        private fun effectiveDeadline(): Deadline? =
            listOfNotNull(
                callOptions.deadline,
                io.grpc.Context
                    .current()
                    .deadline,
            ).minOrNull()

        private fun connectionInfo(): GrpcConnectionInfo? {
            val attributes = runCatching { attributes }.getOrNull() ?: return null
            val sslSession = attributes.get(Grpc.TRANSPORT_ATTR_SSL_SESSION)
            val remoteAddress = attributes.get(Grpc.TRANSPORT_ATTR_REMOTE_ADDR) as? InetSocketAddress
            if (sslSession == null && remoteAddress == null) return null
            return GrpcConnectionInfo(
                scheme = if (sslSession != null) "https" else "http",
                tlsVersion = sslSession?.protocol,
                cipherSuite = sslSession?.cipherSuite,
                remoteAddress = remoteAddress?.address?.hostAddress ?: remoteAddress?.hostString,
            )
        }

        private inner class RecordingListener(
            delegate: Listener<RespT>,
            private val recorder: GrpcCallRecorder,
        ) : ForwardingClientCallListener.SimpleForwardingClientCallListener<RespT>(delegate) {
            override fun onHeaders(headers: Metadata) {
                safely { recorder.onHeaders(headers.toHttpHeaders(), connectionInfo()) }
                super.onHeaders(headers)
            }

            override fun onMessage(message: RespT) {
                safely { recorder.onMessageReceived(message as Any) }
                super.onMessage(message)
            }

            override fun onClose(
                status: Status,
                trailers: Metadata,
            ) {
                safely {
                    recorder.onClose(
                        statusCode = status.code.value(),
                        description = status.description,
                        cause = status.cause,
                        trailers = trailers.toHttpHeaders(),
                        connection = connectionInfo(),
                    )
                }
                super.onClose(status, trailers)
            }
        }
    }

    // Binary metadata is shown as base64.
    private fun Metadata.toHttpHeaders(): List<HttpHeader> =
        keys().flatMap { name ->
            val values =
                if (name.endsWith(Metadata.BINARY_HEADER_SUFFIX)) {
                    getAll(Metadata.Key.of(name, Metadata.BINARY_BYTE_MARSHALLER))?.map { it.toByteString().base64() }
                } else {
                    getAll(Metadata.Key.of(name, Metadata.ASCII_STRING_MARSHALLER))?.toList()
                }
            val isRedacted = name.lowercase() in headersToRedact
            values.orEmpty().map { HttpHeader(name, if (isRedacted) REDACTED else it) }
        }

    // Chucker must never break the app's calls, whatever goes wrong while recording them.
    private inline fun <T> safely(block: () -> T): T? =
        try {
            block()
        } catch (
            @Suppress("TooGenericExceptionCaught") e: Exception,
        ) {
            Logger.error("Failed to record a gRPC call", e)
            null
        }

    private class MarshallerCodec<T>(
        private val marshaller: MethodDescriptor.Marshaller<T>,
    ) : GrpcMessageCodec {
        @Suppress("UNCHECKED_CAST")
        private fun stream(message: Any): InputStream = marshaller.stream(message as T)

        // A message that is itself a stream, as with pass-through marshallers, is the stream the
        // transport reads, so reading it here would take its bytes.
        override fun size(message: Any): Long? {
            if (message is InputStream) return null
            return stream(message).use { stream ->
                if (stream is KnownLength) stream.available().toLong() else stream.countBytes()
            }
        }

        override fun serialize(message: Any): ByteArray? {
            if (message is InputStream) return null
            return stream(message).use { it.readBytes() }
        }

        private fun InputStream.countBytes(): Long {
            val buffer = ByteArray(BUFFER_SIZE)
            var count = 0L
            while (true) {
                val read = read(buffer)
                if (read < 0) return count
                count += read
            }
        }
    }

    /**
     * Assembles a new [ChuckerGrpcInterceptor].
     *
     * @param context An Android [Context].
     */
    public class Builder(
        internal val context: Context,
    ) {
        internal var collector: ChuckerCollector? = null
        internal var maxContentLength = MAX_CONTENT_LENGTH
        internal var headersToRedact = emptySet<String>()
        internal val formatters = mutableListOf<GrpcMessageFormatter>()
        internal val skipMethods = mutableSetOf<String>()
        internal val skipMethodsRegex = mutableSetOf<Regex>()
        internal val skipServices = mutableSetOf<String>()
        internal var sink: GrpcTransactionSink? = null

        /**
         * Sets the [ChuckerCollector] to customize data retention.
         */
        public fun collector(collector: ChuckerCollector): Builder =
            apply {
                this.collector = collector
            }

        /**
         * Sets the maximum length of the messages stored for each direction of a call. Messages
         * past this limit are still counted and measured, but their content isn't stored.
         *
         * Warning: setting this value too high may cause unexpected results.
         */
        public fun maxContentLength(length: Long): Builder =
            apply {
                this.maxContentLength = length
            }

        /**
         * Sets metadata keys whose values will be redacted.
         * They will be replaced with the `**` symbols in the Chucker UI.
         */
        public fun redactHeaders(headerNames: Iterable<String>): Builder =
            apply {
                this.headersToRedact = headerNames.toSet()
            }

        /**
         * Sets metadata keys whose values will be redacted.
         * They will be replaced with the `**` symbols in the Chucker UI.
         */
        public fun redactHeaders(vararg headerNames: String): Builder =
            apply {
                this.headersToRedact = headerNames.toSet()
            }

        /**
         * Adds a [formatter] that converts messages to text. Formatters are applied in the order
         * they were added in, before Chucker's built-in formatting.
         */
        public fun addMessageFormatter(formatter: GrpcMessageFormatter): Builder =
            apply {
                this.formatters += formatter
            }

        /**
         * Skips recording the given methods, named in full, e.g. `ride.v1.RideService/WatchRide`.
         */
        public fun skipMethods(vararg fullMethodNames: String): Builder =
            apply {
                this.skipMethods += fullMethodNames
            }

        /**
         * Skips recording the methods whose full name, e.g. `ride.v1.RideService/WatchRide`,
         * matches [fullMethodNames].
         */
        public fun skipMethods(fullMethodNames: Regex): Builder =
            apply {
                this.skipMethodsRegex += fullMethodNames
            }

        /**
         * Skips recording every method of the given services, e.g. `grpc.health.v1.Health`.
         */
        public fun skipServices(vararg serviceNames: String): Builder =
            apply {
                this.skipServices += serviceNames
            }

        internal fun sink(sink: GrpcTransactionSink): Builder =
            apply {
                this.sink = sink
            }

        /**
         * Creates a new [ChuckerGrpcInterceptor] instance with values defined in this builder.
         */
        public fun build(): ChuckerGrpcInterceptor = ChuckerGrpcInterceptor(this)
    }

    private companion object {
        private const val MAX_CONTENT_LENGTH = 250_000L
        private const val BUFFER_SIZE = 8_192
        private const val PROTOCOL = "gRPC"
        private const val HTTP_METHOD = "POST"
        private const val GRPC_CONTENT_TYPE = "application/grpc"
        private const val REDACTED = "**"

        fun hostOf(authority: String): String = runCatching { URI("//$authority").host }.getOrNull() ?: authority
    }
}
